       count(*) FILTER (WHERE f.flock_no::text = '16')::int AS f16,
       count(*) FILTER (WHERE f.flock_no::text = '17')::int AS f17,
       COALESCE(sum(hb.eggs_set),0)::bigint    AS eggs_set,
       COALESCE(sum(hb.chicks_sold),0)::bigint AS chicks
FROM public.hatch_batches hb JOIN public.flocks f ON f.id = hb.flock_id
WHERE f.flock_no::text IN ('16','17');

SELECT count(*)::int AS rows_missing_hatchery_link
FROM public.hatch_batches hb JOIN public.flocks f ON f.id = hb.flock_id
WHERE f.flock_no::text IN ('16','17') AND hb.hatchery_id IS NULL;

SELECT count(*)::int AS ui_guard_violations
FROM public.hatch_batches hb JOIN public.flocks f ON f.id = hb.flock_id
WHERE f.flock_no::text IN ('16','17')
  AND (COALESCE(hb.hatched_chicks,0) + COALESCE(hb.culled_chicks,0) + COALESCE(hb.rejects,0))
      > (COALESCE(hb.eggs_set,0) - COALESCE(hb.infertile,0) - COALESCE(hb.blasters,0));

SELECT count(*)::int AS untouched_other_rows
FROM public.hatch_batches hb LEFT JOIN public.flocks f ON f.id = hb.flock_id
WHERE f.flock_no IS NULL OR f.flock_no::text NOT IN ('16','17');

